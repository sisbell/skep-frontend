        # span that names none
        beamed = [x for x in ctx.js('window.__skep.links.shown(%s)' % json.dumps(BEAMED)) if ctx.js('window.__skep.links.tailed(%s, %s)' % (json.dumps(BEAMED), json.dumps(x['link']))) is False]

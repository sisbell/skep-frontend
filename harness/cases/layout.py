def inside(a, b):
    """is `a` inside `b`, LABEL_TOL_PX either way?"""
    return a['x'] >= b['x'] - LABEL_TOL_PX and a['y'] >= b['y'] - LABEL_TOL_PX and a['x'] + a['w'] <= b['x'] + b['w'] + LABEL_TOL_PX and a['y'] + a['h'] <= b['y'] + b['h'] + LABEL_TOL_PX


def meets(a, b):
    """do two rects overlap by more than LABEL_TOL_PX each way?"""
    return min(a['x'] + a['w'], b['x'] + b['w']) - max(a['x'], b['x']) > LABEL_TOL_PX and min(a['y'] + a['h'], b['y'] + b['h']) - max(a['y'], b['y']) > LABEL_TOL_PX


def place_of(v, label):
    """a label's place on screen, as the projection gives it; None where the frame drew no such place — and for a
    connection's count, whose place is its stroke (`on_stroke`)"""
    kind, place = label['kind'], label['place']
    if kind == 'board':
        return v['board']
    if kind in ('cluster', 'frame'):
        return next((a['rect'] for a in v['accounts'] if a['place'] == place), None)
    if kind == 'mark':
        return next((m['rect'] for m in v['marks'] if m['place'] == place), None)
    if kind == 'doc':
        return v['docs'].get(place)
    return None


def on_stroke(v, label, line):
    """does a connection's count stand on its stroke: its line's centre on the segment between its connection's two
    places' centres, as the projection gives them, LABEL_TOL_PX either way, and the line inside the visible view?"""
    c = next((c for c in v['connections'] if c['place'] == label['place']), None)
    if c is None:
        return False
    a, b, q = c['ends'][0], c['ends'][1], line['rect']
    px, py = q['x'] + q['w'] / 2, q['y'] + q['h'] / 2
    dx, dy = b['x'] - a['x'], b['y'] - a['y']
    t = max(0, min(1, ((px - a['x']) * dx + (py - a['y']) * dy) / ((dx * dx + dy * dy) or 1)))
    return math.hypot(a['x'] + dx * t - px, a['y'] + dy * t - py) <= LABEL_TOL_PX and inside(q, v['seen'])


def at_tail(v, label, line):
    """does a tail's label stand at its tail's end: its lines' left edge TAIL_GAP_PX past the end of the tail's stroke, its first
    line centred on the stroke's height and every later one below it, LABEL_TOL_PX either way, inside the visible view?"""
    t = next((t for t in v['tails'] if t['key'] == label['place']), None)
    if t is None:
        return False
    first, q = label['lines'][0]['rect'], line['rect']
    return (abs(q['x'] - (t['to']['x'] + TAIL_GAP_PX)) <= LABEL_TOL_PX and abs(first['y'] + first['h'] / 2 - t['from']['y']) <= LABEL_TOL_PX
            and q['y'] >= first['y'] - LABEL_TOL_PX and inside(q, v['seen']))



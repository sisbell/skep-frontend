/**
 * A document's state as its corner states it, in foundations' one order
 * (§3.1; C-346): withheld, its withheld box's words, its owner by the one
 * owner rule (`originOwner`); nothing the board will say of it, the words for
 * that (`L.far.unregistered`); every other document its kind first (`kind`),
 * in its slot, then by it — published, where it states its box's chain
 * (`members`, `statedChain`), its version statement: "version ⟨k⟩ of ⟨n⟩",
 * its own number at a pinned version, the head's at the bare address
 * (FP-22), "version ⟨k⟩" while the board lags; then its state, its venue's
 * clause before it on a notebook (P7): "no versions yet" where its chain
 * holds no member, its own version at a pinned one, "the latest version" at
 * the bare address, the venue's clause alone while the board lags (FP-23); a
 * draft, its kept word (B3-S2), beneath it the face standing at its corner
 * where one stands (`ArticleView.face`; B3-S2; foundations §3.1), then its
 * chip (C-28) — the moved scene's held version, which is no document and has
 * no chip, its line in the place of the kept word and the chip
 * (`ArticleView.held`; B3-S2; D6 BM-14); being read or not read, its slot
 * alone. The one rule the corner draws its state by (`cornerHTML`)
 * and the ARIA mirror's item voices it by (`cornerLead`, `cornerWords`; R94).
 * @param {Doc} d
 * @param {CornerFacts} v
 * @returns {[StateItem, ...StateItem[]]}
 */
function stateItems(d, v) {
  const k = memberOf(d.addr);
  /** an item: a string filled, a usual state's glyph, and what else it carries */
  const item = (/** @type {StateItem['cls']} */ cls, /** @type {string} */ id, /** @type {Record<string, string | number>} */ vals, /** @type {string | null} */ glyph = null, /** @type {Partial<StateItem>} */ more = {}) =>
    /** @type {StateItem} */ ({ cls, id, vals, faces: {}, glyph, members: null, ...more });
  if (d.refused === 'withheld') return [item('st', 'F.corner.withheld', { owner: v.originOwner(d.addr) }, null, { faces: { owner: 'ident' } })];
  if (d.refused === 'unregistered') return [item('st', 'L.far.unregistered', {})];
  const kind = item('kind', KIND_WORDS[v.kind], {});
  if (v.kind === 'published') {
    const n = v.members !== undefined ? v.members : d.members;
    /** a state's words keyed by venue (P7): on a notebook, its clause before them */
    const venued = (/** @type {string} */ id, /** @type {Record<string, string | number>} */ vals, /** @type {string} */ glyph) =>
      (v.notebook ? item('st', 'L.corner.venue', { venue: t('F.published.notebook'), state: t(id, vals) }, glyph) : item('st', id, vals, glyph));
    const st = d.meta && d.meta.birth === null && !k ? venued('F.corner.no-versions', {}, 'L.corner.bare')
      : k ? venued('F.corner.pinned', { k }, 'L.corner.pinned')
        : v.lags ? (v.notebook ? item('st', 'F.published.notebook', {}, 'L.corner.bare') : null)
          : venued('F.corner.latest', {}, 'L.corner.bare');
    const of = statedChain(d, n);
    /** @type {[StateItem, ...StateItem[]]} */
    const out = [kind];
    if (of != null) out.push(v.lags ? item('version', 'L.version', { k: k || of }) : item('version', 'F.version-of', { k: k || of, n: of }, null, { members: of }));
    if (st) out.push(st);
    return out;
  }
  if (v.kind === 'draft' && v.held) return [kind, item('held', 'B3.history.held', {})];
  if (v.kind === 'draft') {
    const face = v.face ? [item('face', v.face.line.id, {}, null, { face: v.face })] : [];
    return [kind, item('kept', v.kept ? KEPT_WORDS[v.kept.word] : '', {}), ...face, item('chip', v.localTrust ? 'C-28.flag-on' : 'C-28', {}, 'L.corner.draft')];
  }
  return [kind];
}

/**
 * A corner's first item in words (`stateItems`): the document's kind in its
 * slot's words (`kindWord`) — "being read" while it is — or, at a document a
 * read refused, its own words. What the ARIA mirror's item and a reading
 * scene's pane's name lead with (R94).
 * @param {Doc} d
 * @param {CornerFacts} v
 * @returns {string}
 */
export const cornerLead = (d, v) => { const [i] = stateItems(d, v); return t(i.id, i.vals); };

/**
 * A document's state as its corner states it after its first item, whole
 * (`stateItems`): each item's words — a draft's kept word where a state is
 * set, the face beneath it in its words whole (`faceWords`) — joined as the
 * ARIA mirror's item voices them after the document's first line (R94); ''
 * where the corner states none past its first item.
 * @param {Doc} d
 * @param {CornerFacts} v
 * @returns {string}
 */
export const cornerWords = (d, v) => stateItems(d, v).slice(1).filter((i) => i.id).map((i) => (i.face ? faceWords(i.face) : t(i.id, i.vals))).join(', ');

/**
 * A corner's state item as markup (`stateItems`): the kind its slot
 * (`kindHTML`), its words in either form; a draft's kept word its kept line
 * (`keptLineHTML`), its statement after it where `statement` asks; the face
 * standing beneath it in the form asked (`faceHTML`); a usual
 * state, compact, its glyph named by its words, which assistive technology
 * reads, the act that opens the corner whole (FP-26), and, the corner opened
 * whole on it, its words the act that compacts it again, each saying whether
 * the corner stands opened (`ArticleView.opened`); else its words, an owner
 * it names in the identifier's face, a draft's chip marked so, the held
 * version's line carrying its string and the version statement carrying the
 * count it is of — on the plane the act that opens the versions list (D5
 * K-57). Its words alone, no act, where the view asks none
 * (`ArticleView.acts`); every act a native button (`actHTML`).
 * @param {StateItem} i
 * @param {ArticleView} v
 * @param {boolean} compact
 * @param {boolean} [statement]
 */
function stateHTML(i, v, compact, statement = true) {
  if (i.cls === 'kind') return kindHTML(v);
  if (i.cls === 'kept') return keptLineHTML(v, statement);
  if (i.face) return faceHTML(i.face, v, compact);
  const extra = i.cls === 'chip' ? ' data-chip="1"' : i.cls === 'held' ? ` data-string="${esc(i.id)}"` : i.members != null ? ` data-members="${i.members}"` : '';
  const words = Object.keys(i.faces).length ? htmlIn(i.id, i.vals, i.faces) : esc(t(i.id, i.vals)), acts = v.acts !== false;
  if (compact && i.glyph) {
    return acts ? actHTML(`${i.cls} glyph`, `${extra} data-whole aria-expanded="${!!v.opened}" aria-label="${esc(t(i.id, i.vals))}"`, esc(t(i.glyph)))
      : `<span class="${i.cls} glyph"${extra} role="img" aria-label="${esc(t(i.id, i.vals))}">${esc(t(i.glyph))}</span>`;
  }
  if (acts && i.glyph && v.opened) return actHTML(i.cls, `${extra} data-whole aria-expanded="true"`, words);
  if (acts && i.cls === 'version' && !v.scene) return actHTML(i.cls, extra, words);
  return `<span class="${i.cls}"${extra}>${words}</span>`;
}

/**
 * A string's width filled, in em at 1 em (`Measure`): each stretch of its
 * words in the client's face, each value a token names in the face `faces`
 * gives it.
 * @param {string} id
 * @param {Record<string, string | number>} vals
 * @param {Record<string, Face>} faces
 * @param {Measure} measure
 */
function filledEm(id, vals, faces, measure) {
  return t(id).split(/⟨([^⟩]+)⟩/).reduce((w, s, k) => w + (k % 2 ? measure(String(vals[s] ?? `⟨${s}⟩`), faces[s] || 'client') : s ? measure(s, 'client') : 0), 0);
}

/**
 * @typedef {Object} CornerItem — one item of a corner in foundations' one order (`cornerItems`): its markup and its words in the form asked, its width, and how it meets a narrow room
 * @property {string} cls its class
 * @property {string} html its markup
 * @property {string} words its words as a person reads them
 * @property {number} em its width in em of the corner's size, as the view measures its words (`Measure`): its slot's, where it has one of fixed width — the kind's, a kept word's
 * @property {boolean} yields it may fold into the corner's count where a row cannot hold it: the offered read alone; every other item never yields (foundations §3.1)
 */

/**
 * The corner's items in foundations' one order (§3.1): its document's kind,
 * its version statement and its state (`stateItems`) — at a pinned version
 * its own number of the count its box's document holds (`members`), so the
 * corner names the version its box shows and offers the versions list there
 * too (FP-22); at a published document in a reading scene's pane, where the
 * version its pane reads lacks the passage its act carried, a line saying so
 * (`lacks`); its act reading another version in its place (`read`; D5 K-57;
 * FP-23) — a pane's, and on the plane the newer version a newer version's
 * arrival offers, an act (`actHTML`), its words alone where the view asks no
 * act (`ArticleView.acts`); the whole-document link count (rule (i)). Compact (FP-26): an
 * edition's state its version marker — unlit at the bare address, lit at a
 * pinned version (foundations §3.1) — and a draft's chip a glyph, each named
 * by its whole words, the act that opens the corner whole (`stateHTML`); the
 * face its compact form (`faceHTML`); the kind in its slot, "version ⟨k⟩ of
 * ⟨n⟩", the whole-document count, the kept word in its slot, the held
 * version's line and the state of a document a read refused keep their words.
 * Each with its words and its width (`CornerItem`): the kind, its version
 * statement, the state, a draft's kept word, the face, its chip, the held
 * version's line and the whole-document count never yield; the offered read
 * does.
 * @param {Doc} d
 * @param {ArticleView} v
 * @param {boolean} [compact] the compact form
 * @param {boolean} [statement] a draft's kept statement, opened, stands after its word; false where its holder opens it elsewhere (`keptLineHTML`)
 * @returns {CornerItem[]}
 */
export function cornerItems(d, v, compact = false, statement = true) {
  /** @type {CornerItem[]} */
  const out = stateItems(d, v).map((i) => {
    if (i.face) {
      const said = compact && i.face.compact ? i.face.compact.text : faceWords(i.face);
      return { cls: i.cls, html: faceHTML(i.face, v, compact), words: said, em: v.measure(said, 'client'), yields: false };
    }
    const words = i.cls === 'kind' ? (v.kind === 'reading' ? '' : t(i.id)) : i.cls === 'kept' ? (i.id ? t(i.id) : '') : t(i.id, i.vals), glyph = compact && i.glyph ? t(i.glyph) : null;
    const em = i.cls === 'kind' ? kindSlotEm(v.measure) : i.cls === 'kept' ? keptSlotEm(v.measure) : glyph != null ? v.measure(glyph, 'client') : filledEm(i.id, i.vals, i.faces, v.measure) + (i.cls === 'chip' ? 0.8 : 0);
    return { cls: i.cls, html: stateHTML(i, v, compact, statement), words, em, yields: false };
  });
  /** an item of words alone */
  const words = (/** @type {string} */ cls, /** @type {string} */ text, /** @type {string} */ html, yields = false) => out.push({ cls, html, words: text, em: v.measure(text, 'client'), yields });
  if (!d.refused && v.kind === 'published') {
    if (v.lacks != null) { const s = t('F.floating.member', { k: v.lacks }); words('lacks', s, `<span class="lacks">${esc(s)}</span>`); }
    if (v.read != null) {
      const s = t('F.versions.read', { k: v.read });
      words('read', s, v.acts === false ? `<span class="read">${esc(s)}</span>` : actHTML('read', ` data-read="${v.read}"`, esc(s)), true);
    }
  }
  if (v.wholeLinks > 0) { const s = v.wholeLinks === 1 ? t('F.whole-links.1') : t('F.whole-links', { n: v.wholeLinks }); words('whole-links', s, `<span class="whole-links">${esc(s)}</span>`); }
  return out;
}

